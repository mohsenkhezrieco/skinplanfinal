a(r.ageing_retinoid_advanced[0]==='ord_retinal_02','The Ordinary Retinal 0.2% not correctly ranked in advanced efficacy');
a(html.includes("d.kind==='ageing_retinoid'?'ageing_retinoid_starter':d.kind"),'Automatic ageing pathway not decoupled from advanced ranking');
