for(const b of expectedBrands)a(brands.has(b),'Missing brand '+b);
for(const role of Object.keys(r))for(const id of r[role])a(ids.has(id),`Missing ${id} from products for ${role}`);
a(ids.has('lrp_effaclar_cleanser'),'LRP oily cleanser missing');
a(r.cleanser_oily.slice(0,3).includes('lrp_effaclar_cleanser'),'LRP Effaclar must rank near top of oily cleansers');
a(!ids.has('eucerin_dp_cleanser'),'Acid correcting cleanser must not remain a base cleanser');
