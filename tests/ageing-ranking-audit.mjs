import fs from 'node:fs';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const m=html.match(/const RANKINGS=(\{.*?\});\nconst ROLE_LABELS=/s);
if(!m) throw new Error('RANKINGS not found');
const r=JSON.parse(m[1]);
const starter=['lrp_retinol_b3','avene_retinal_night','cerave_skin_renewing_retinol','neutro_retinol','inkey_retinol','ord_granactive'];
const advanced=['ord_retinal_02','inkey_advanced_retinal','neutro_retinol_intense','lrp_retinol_b3','avene_retinal_night','neutro_retinol','cerave_skin_renewing_retinol','inkey_retinol','ord_granactive'];
if(JSON.stringify(r.ageing_retinoid_starter)!==JSON.stringify(starter)) throw new Error('Starter ageing ranking mismatch');
if(JSON.stringify(r.ageing_retinoid_advanced)!==JSON.stringify(advanced)) throw new Error('Advanced ageing ranking mismatch');
if(r.ageing_retinoid_advanced.indexOf('ord_retinal_02')!==0) throw new Error('The Ordinary Retinal 0.2% must lead the advanced efficacy table');
console.log('PASS — v17.13 starter + advanced ageing rankings');
